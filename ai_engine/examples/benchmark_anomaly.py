"""Synthetic benchmark of the water anomaly detectors -> docs/evaluation/anomaly_synthetic_benchmark.md

All data is SYNTHETIC (data_class simulated). Results are "simulation-tested" and say nothing
about detection rates on real farms. Usage: uv run python examples/benchmark_anomaly.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from qatra_ai.evaluation.anomaly_benchmark import run_benchmark

REPORT = (
    Path(__file__).resolve().parents[2] / "docs" / "evaluation" / "anomaly_synthetic_benchmark.md"
)
SEEDS = range(20)


def sweep(fault: str, param: str, values: list[float]) -> pd.DataFrame:
    rows = []
    for v in values:
        s, fa = run_benchmark(seeds=SEEDS, faults=(fault,), gen_kwargs={param: v})
        rows.append(
            {
                param: v,
                "detection_rate": s.iloc[0].detection_rate,
                "median_time_to_detect_h": s.iloc[0].median_ttd_h,
                "clean_false_alarms_per_week": round(
                    fa.set_index("run").loc["clean", "mean_per_week"], 3
                ),
            }
        )
    return pd.DataFrame(rows)


def main() -> None:
    main_tables = []
    for noise in (0.02, 0.04, 0.06):
        s, fa = run_benchmark(seeds=SEEDS, gen_kwargs={"meter_noise_rel": noise})
        s.insert(0, "meter_noise", f"{noise:.0%}")
        main_tables.append(s)
        fa_clean = fa.set_index("run").loc["clean", "mean_per_week"]
        main_tables[-1]["clean_false_alarms_per_week"] = round(fa_clean, 3)
    main = pd.concat(main_tables, ignore_index=True)
    leak = sweep("slow_leak", "slow_leak_m3h", [0.03, 0.05, 0.08, 0.1, 0.15, 0.2])
    burst = sweep("burst_zone_B", "burst_fraction", [0.05, 0.1, 0.15, 0.2, 0.4])

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(
        f"""# Water anomaly detection: synthetic benchmark

> **Simulation-tested only.** Faults, meters and schedules are generated by
> `qatra_ai/evaluation/synthetic_water.py`, written by the same team as the detectors. These
> numbers show the detectors behave as designed and where their sensitivity ends. They are
> **not** field detection rates. Real systems have faults the generator does not imagine.

## Setup

- One well pump, 3 zones (design 10 / 12 / 8 m³/h; true flows ×0.95 / ×1.03 / ×0.90, unknown to
  the detector), daily schedule, 15 % skipped days, hourly data, 42 days per run.
- The first 7 days are assumed fault-free and used to calibrate per-zone flows and noise.
- Meters: Gaussian noise (relative + 0.03 m³/h absolute), readings clipped at 0.
- {len(SEEDS)} random seeds per configuration. Every run is paired with a clean run (no faults)
  to measure false alarms.
- A fault counts as detected if an event of an expected kind overlaps the fault window
  (+24 h grace). False alarms = events overlapping no fault window.

## All fault types, by meter noise

{main.to_markdown(index=False)}

## Sensitivity: slow mainline leak (meter noise 2 %)

{leak.to_markdown(index=False)}

## Sensitivity: burst in zone B (extra flow as a fraction of design flow; noise 2 %)

{burst.to_markdown(index=False)}

## Interpretation

- Under these synthetic conditions, leaks below roughly 0.05 m³/h (about 1.2 m³/day) are not
  separable from meter noise, and bursts adding less than about 10 % of a zone's flow are
  mostly missed.
- Adaptive thresholds keep false alarms low as meter noise grows. The price is reduced
  sensitivity (e.g. clogging detection at 6 % noise).
- Events carry hypotheses, evidence and recommended checks. No event names a person or
  asserts misconduct; a test bans accusatory terms.

## Known gaps

- Fault shapes are idealised (step changes). Real leaks grow, are intermittent, and interact.
- The training window is assumed fault-free; a fault present from day 1 becomes the baseline.
- Pump head changes (well drawdown) and seasonal schedule changes are not simulated.
- Thresholds have not been tuned or validated on any real system.
""",
        encoding="utf-8",
    )
    print(main.to_string(index=False))
    print(f"\nReport written to {REPORT}")


if __name__ == "__main__":
    main()
